import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import {fileURLToPath} from 'node:url';
import {buildLearnRoomReport} from '../../../src/tracks/learn-room/report.ts';
import {buildDistributionMessages} from '../../../src/tracks/distribution/prompt.ts';
import {loadDistributionData} from '../../../src/shared/dataset.ts';

// Offline only: verify the declared final run and summarize saved evidence.
const here=path.dirname(fileURLToPath(import.meta.url));
const read=p=>JSON.parse(fs.readFileSync(p,'utf8'));
const saved=read(path.join(here,'report.json'));
assert.deepEqual(buildLearnRoomReport(here),saved);
assert.equal(saved.complete,true);
const c=saved.manifest.config, data=loadDistributionData();
assert.equal(c.partition,'evaluation');
assert.deepEqual(c.targets,data.split.evaluation);
assert.equal(c.targets.length,45);
assert.deepEqual(c.reference,data.split.reference);
assert.equal(c.reference.length,90);
assert.deepEqual(c.strategies,['none','random','similar','agent']);
assert.equal(c.model,'z-ai/glm-5.3-flash');
assert.equal(c.agentPolicy,'transfer-check-v1');
assert.equal(c.settings.maxTokens,4000);
assert.equal(c.settings.temperature,0);
assert.equal(c.budget,3);assert.equal(c.maxActions,8);assert.equal(c.maxModelCalls,8);assert.equal(c.seed,7);
assert.equal(c.spending.limitUsd,.25);assert.equal(c.spending.providerTag,'relace/fp4');
for(const row of saved.rows.filter(r=>r.strategy==='none'))assert.deepEqual(row.request.messages,buildDistributionMessages(row.word));
const ledger=read(path.join(here,'spending.json'));
assert.deepEqual(ledger.policy,c.spending);
const attempts=saved.rows.flatMap(r=>r.attempts.map(a=>({strategy:r.strategy,day:r.day,status:a.status,error:a.error,finishReason:a.response?.choices?.[0]?.finish_reason,provider:a.provider})));
assert.equal(attempts.length,ledger.entries.length);
const accountedUsd=ledger.entries.reduce((sum,e)=>sum+(e.chargedUnits??e.reservedUnits),0)/1e9;
assert(accountedUsd<=c.spending.limitUsd);
const comparisons=saved.comparisons.map(({pairs,...rest})=>({...rest,wins:pairs.filter(p=>p.scoreGain>0).length,ties:pairs.filter(p=>p.scoreGain===0).length,losses:pairs.filter(p=>p.scoreGain<0).length}));
const development=read(path.join(here,'../comparisons/glm-5-3-flash-policy-repeats/analysis.json'));
const result={verification:{reportReplays:true,fullFrozenEvaluationPartition:true,referencePoolUnchanged:true,directDistributionMessagesMatch:true,withinAuthorizedBudget:true},sourceCommit:'94a00df3',runId:saved.manifest.id,createdAt:saved.manifest.createdAt,completedAt:saved.manifest.completedAt,summaries:saved.summaries,baselines:saved.baselines,comparisons,developmentContext:saved.summaries.map(s=>({strategy:s.strategy,developmentThreeRunMean:development.strategies.find(d=>d.strategy===s.strategy).transfer.scores.mean,finalScore:s.score,note:'Different target partitions; this difference is not a policy effect.'})),cost:{capUsd:ledger.policy.limitUsd,reportedUsd:saved.summaries.reduce((sum,s)=>sum+s.costUsd.known,0),accountedUsd,unknownRequests:ledger.entries.filter(e=>e.chargedUnits===null).length},httpAttempts:attempts.length,errors:attempts.filter(a=>a.status!=='response'),lengthStops:attempts.filter(a=>a.finishReason==='length'),earlySubmissions:saved.rows.filter(r=>r.strategy==='agent'&&r.outcome.inspections<3).map(r=>({day:r.day,word:r.word,inspections:r.outcome.inspections})),agentTargetGains:saved.comparisons.find(p=>p.strategy==='agent'&&p.control==='none').pairs.map(p=>({...p,word:saved.rows.find(r=>r.day===p.day).word}))};
fs.writeFileSync(path.join(here,'analysis.json'),JSON.stringify(result,null,2)+'\n');
console.log(JSON.stringify({...result,agentTargetGains:undefined},null,2));
